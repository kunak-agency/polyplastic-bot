// Демо-сценарии по таблице 2.3 UX-спецификации. Тексты короткие, своими словами и помечены
// «(демо)»: настоящих формулировок ТЗ и регламентов здесь нет. Знакомство и согласие —
// системные сообщения бота (services/bot_render.go), в шаги не входят.

// demoTag — пометка в каждом тексте.
const demoTag = " (демо)"

// step — шаг с текстами на «ты» и «вы».
func step(day int, hhmm, kind, title, ty, vy string, buttons ...string) domain.ScenarioStep {
	s := domain.ScenarioStep{
		DayOffset: day, Time: hhmm, Kind: kind, Title: title,
		TextTy: ty + demoTag, TextVy: vy + demoTag, WorkHoursOnly: true,
		Sites: domain.StringList{}, Buttons: domain.ButtonList{},
	}
	for _, b := range buttons {
		s.Buttons = append(s.Buttons, domain.StepButton{Label: b})
	}
	return s
}

func only(s domain.ScenarioStep, sites ...string) domain.ScenarioStep {
	s.Sites = sites
	return s
}

func survey(s domain.ScenarioStep, scale string, threshold int, questions ...string) domain.ScenarioStep {
	s.Kind = domain.KindSurvey
	sv := &domain.Survey{Scale: scale, Threshold: threshold}
	for _, q := range questions {
		sv.Questions = append(sv.Questions, domain.SurveyQuestion{Text: q})
	}
	s.Survey = sv
	return s
}

func choice(s domain.ScenarioStep, question string, options ...string) domain.ScenarioStep {
	s.Kind = domain.KindSurvey
	s.Survey = &domain.Survey{Scale: domain.ScaleChoice, Questions: []domain.SurveyQuestion{{Text: question, Options: options}}}
	return s
}

